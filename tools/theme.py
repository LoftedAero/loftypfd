"""Generates src/core/theme.lua from the vendored design system.

    .venv/Scripts/python tools/theme.py

The radios cannot read CSS, so the color tokens are carried over as RGB
triples: the light values from lofted-aero.css's :root, with the dark
theme's overrides from lofted-aero-dark.css. Names lose their --la- prefix
and become camelCase (--la-orange-deep is orangeDeep, --la-ink-2 is ink2).
tools/test.py fails if the file differs from what this produces, so the
colors only ever change by vendoring a new release.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
DESIGN = ROOT / "design"
OUT = ROOT / "src" / "core" / "theme.lua"

TOKEN = re.compile(r"--la-([a-z0-9-]+)\s*:\s*([^;]+);")


def block(css, selector):
    start = css.index(selector)
    open_brace = css.index("{", start)
    return css[open_brace + 1:css.index("}", open_brace)]


def tokens(text):
    return {name: value.strip() for name, value in TOKEN.findall(text)}


def rgb(value, table):
    ref = re.fullmatch(r"var\(--la-([a-z0-9-]+)\)", value)
    if ref:
        return rgb(table[ref.group(1)], table)
    hex_ = re.fullmatch(r"#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})", value)
    if not hex_:
        return None
    h = hex_.group(1)
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def camel(name):
    parts = name.split("-")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def palette(table):
    out = {}
    for name in table:
        value = rgb(table[name], table)
        if value is not None:
            out[camel(name)] = value
    return out


def generate():
    version = json.loads((DESIGN / "lofted-aero.json").read_text(encoding="utf-8"))["version"]
    light = tokens(block((DESIGN / "lofted-aero.css").read_text(encoding="utf-8"), ":root {"))
    dark = dict(light)
    dark.update(tokens(block((DESIGN / "lofted-aero-dark.css").read_text(encoding="utf-8"),
                             ":root[data-theme='dark'] {")))
    lines = [
        "-- Generated by tools/theme.py from design/lofted-aero.css and",
        "-- design/lofted-aero-dark.css, Lofted Aero design system %s. Do not edit:" % version,
        "-- change the design system, vendor the release, and run the generator.",
        "return {",
    ]
    for theme, table in (("light", light), ("dark", dark)):
        lines.append("  %s = {" % theme)
        for name, (r, g, b) in sorted(palette(table).items()):
            lines.append("    %s = { %d, %d, %d }," % (name, r, g, b))
        lines.append("  },")
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_text(generate(), encoding="utf-8", newline="\n")
    print("wrote " + OUT.relative_to(ROOT).as_posix())
